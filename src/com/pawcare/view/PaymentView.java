    private void loadAppointmentDropdown() {
    try {
        cmbAppointment.removeAllItems();
        appointmentIdsForCombo.clear();
        appointmentLabelsById.clear();

        for (Map<String, Object> row : appointmentController.getAppointmentDetailsList()) {
            int appointmentId = (int) row.get("appointment_id");
            String label = row.get("customer_name") + " - " + row.get("pet_name")
                    + " - " + row.get("appointment_date") + " " + row.get("appointment_time");
            cmbAppointment.addItem(label);
            appointmentIdsForCombo.add(appointmentId);
            appointmentLabelsById.put(appointmentId, label);
        }
    } catch (SQLException ex) {
        showError("Could not load appointments: " + ex.getMessage());
    }
}

private void loadPaymentTable() {
    try {
        DefaultTableModel model = (DefaultTableModel) tblPayments.getModel();
        model.setRowCount(0);

        for (Payment p : paymentController.getAllPayments()) {
            String appointmentLabel = appointmentLabelsById.getOrDefault(
                    p.getAppointmentId(), "Appointment #" + p.getAppointmentId());
            model.addRow(new Object[]{
                p.getPaymentId(),
                appointmentLabel,
                p.getAmount(),
                p.getPaymentMethod(),
                p.getPaymentDate(),
                p.getPaymentStatus()
            });
        }
    } catch (SQLException ex) {
        showError("Could not load payments: " + ex.getMessage());
    }
}

private BigDecimal parseAmount() {
    try {
        return new BigDecimal(txtAmount.getText().trim());
    } catch (NumberFormatException ex) {
        throw new IllegalArgumentException("Amount must be a valid number, e.g. 2500.00");
    }
}

private LocalDate parsePaymentDate() {
    try {
        return LocalDate.parse(txtPaymentDate.getText().trim());
    } catch (DateTimeParseException ex) {
        throw new IllegalArgumentException("Date must be in yyyy-MM-dd format, e.g. 2026-09-20");
    }
}

private void clearForm() {
    if (cmbAppointment.getItemCount() > 0) cmbAppointment.setSelectedIndex(0);
    txtAmount.setText("");
    if (cmbPaymentMethod.getItemCount() > 0) cmbPaymentMethod.setSelectedIndex(0);
    txtPaymentDate.setText("");
    if (cmbPaymentStatus.getItemCount() > 0) cmbPaymentStatus.setSelectedIndex(0);
    selectedPaymentId = 0;
    tblPayments.clearSelection();
    lblMessage.setText("");
}

private void showError(String message) {
    lblMessage.setForeground(Color.RED);
    lblMessage.setText(message);
}

private void showSuccess(String message) {
    lblMessage.setForeground(new Color(0, 128, 0));
    lblMessage.setText(message);
}

