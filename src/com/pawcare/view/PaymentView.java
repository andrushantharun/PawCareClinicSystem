    private void tblPaymentsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPaymentsMouseClicked
         int row = tblPayments.getSelectedRow();
    if (row == -1) return;

    DefaultTableModel model = (DefaultTableModel) tblPayments.getModel();
    selectedPaymentId = (int) model.getValueAt(row, 0);

    try {
        for (Payment p : paymentController.getAllPayments()) {
            if (p.getPaymentId() == selectedPaymentId) {
                int comboIndex = appointmentIdsForCombo.indexOf(p.getAppointmentId());
                if (comboIndex >= 0) cmbAppointment.setSelectedIndex(comboIndex);

                txtAmount.setText(p.getAmount().toString());
                cmbPaymentMethod.setSelectedItem(p.getPaymentMethod());
                txtPaymentDate.setText(p.getPaymentDate().toString());
                cmbPaymentStatus.setSelectedItem(p.getPaymentStatus());
                break;
            }
        }
        lblMessage.setText("");
    } catch (SQLException ex) {
        showError("Could not load payment: " + ex.getMessage());
    }
    }//GEN-LAST:event_tblPaymentsMouseClicked

