    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
         try {
        int index = cmbAppointment.getSelectedIndex();
        if (index < 0) {
            showError("Please select an appointment.");
            return;
        }
        int appointmentId = appointmentIdsForCombo.get(index);

        Payment payment = new Payment(
                appointmentId,
                parseAmount(),
                (String) cmbPaymentMethod.getSelectedItem(),
                parsePaymentDate(),
                (String) cmbPaymentStatus.getSelectedItem()
        );
        paymentController.addPayment(payment);
        showSuccess("Payment recorded successfully.");
        clearForm();
        loadPaymentTable();
    } catch (IllegalArgumentException ex) {
        showError(ex.getMessage());
    } catch (SQLException ex) {
        showError("Database error: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (selectedPaymentId == 0) {
        showError("Select a payment from the table first.");
        return;
    }
    try {
        int index = cmbAppointment.getSelectedIndex();
        if (index < 0) {
            showError("Please select an appointment.");
            return;
        }
        int appointmentId = appointmentIdsForCombo.get(index);

        Payment payment = new Payment(
                selectedPaymentId,
                appointmentId,
                parseAmount(),
                (String) cmbPaymentMethod.getSelectedItem(),
                parsePaymentDate(),
                (String) cmbPaymentStatus.getSelectedItem()
        );
        paymentController.updatePayment(payment);
        showSuccess("Payment updated successfully.");
        clearForm();
        loadPaymentTable();
    } catch (IllegalArgumentException ex) {
        showError(ex.getMessage());
    } catch (SQLException ex) {
        showError("Database error: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (selectedPaymentId == 0) {
        showError("Select a payment from the table first.");
        return;
    }
    int confirm = javax.swing.JOptionPane.showConfirmDialog(
            this, "Delete this payment record?", "Confirm Delete",
            javax.swing.JOptionPane.YES_NO_OPTION);
    if (confirm != javax.swing.JOptionPane.YES_OPTION) return;

    try {
        paymentController.deletePayment(selectedPaymentId);
        showSuccess("Payment deleted.");
        clearForm();
        loadPaymentTable();
    } catch (SQLException ex) {
        showError("Database error: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

