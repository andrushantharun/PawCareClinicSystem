    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
         try {
        Customer selectedCustomer = (Customer) cmbCustomer.getSelectedItem();
        int customerId = (selectedCustomer != null) ? selectedCustomer.getCustomerId() : 0;
        int age = parseAge();

        Pet pet = new Pet(
                customerId,
                txtPetName.getText().trim(),
                txtSpecies.getText().trim(),
                txtBreed.getText().trim(),
                age,
                (String) cmbGender.getSelectedItem()
        );
        petController.addPet(pet);
        showSuccess("Pet added successfully.");
        clearForm();
        loadPetTable();
    } catch (IllegalArgumentException ex) {
        showError(ex.getMessage());
    } catch (SQLException ex) {
        showError("Database error: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (selectedPetId == 0) {
        showError("Select a pet from the table first.");
        return;
    }
    try {
        Customer selectedCustomer = (Customer) cmbCustomer.getSelectedItem();
        int customerId = (selectedCustomer != null) ? selectedCustomer.getCustomerId() : 0;
        int age = parseAge();

        Pet pet = new Pet(
                selectedPetId,
                customerId,
                txtPetName.getText().trim(),
                txtSpecies.getText().trim(),
                txtBreed.getText().trim(),
                age,
                (String) cmbGender.getSelectedItem()
        );
        petController.updatePet(pet);
        showSuccess("Pet updated successfully.");
        clearForm();
        loadPetTable();
    } catch (IllegalArgumentException ex) {
        showError(ex.getMessage());
    } catch (SQLException ex) {
        showError("Database error: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (selectedPetId == 0) {
        showError("Select a pet from the table first.");
        return;
    }
    int confirm = javax.swing.JOptionPane.showConfirmDialog(
            this, "Delete this pet?", "Confirm Delete",
            javax.swing.JOptionPane.YES_NO_OPTION);
    if (confirm != javax.swing.JOptionPane.YES_OPTION) return;

    try {
        petController.deletePet(selectedPetId);
        showSuccess("Pet deleted.");
        clearForm();
        loadPetTable();
    } catch (SQLException ex) {
        showError("Database error: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

