    private int parseAge() {
    try {
        return Integer.parseInt(txtAge.getText().trim());
    } catch (NumberFormatException ex) {
        throw new IllegalArgumentException("Age must be a whole number.");
    }
}

    private void loadCustomerDropdown() {
    try {
        cmbCustomer.removeAllItems();
        List<Customer> customers = customerController.getAllCustomers();
        for (Customer c : customers) {
            cmbCustomer.addItem(c);
        }
    } catch (SQLException ex) {
        showError("Could not load customers: " + ex.getMessage());
    }
}

private void loadPetTable() {
    try {
        DefaultTableModel model = (DefaultTableModel) tblPets.getModel();
        model.setRowCount(0);

        for (Pet p : petController.getAllPets()) {
            model.addRow(new Object[]{
                p.getPetId(),
                customerNameFor(p.getCustomerId()),
                p.getPetName(),
                p.getSpecies(),
                p.getBreed(),
                p.getAge(),
                p.getGender()
            });
        }
    } catch (SQLException ex) {
        showError("Could not load pets: " + ex.getMessage());
    }
}

private String customerNameFor(int customerId) {
    for (int i = 0; i < cmbCustomer.getItemCount(); i++) {
        Customer c = (Customer) cmbCustomer.getItemAt(i);
        if (c.getCustomerId() == customerId) {
            return c.getFullName();
        }
    }
    return "Unknown";
}

private void clearForm() {
    if (cmbCustomer.getItemCount() > 0) cmbCustomer.setSelectedIndex(0);
    txtPetName.setText("");
    txtSpecies.setText("");
    txtBreed.setText("");
    txtAge.setText("");
    if (cmbGender.getItemCount() > 0) cmbGender.setSelectedIndex(0);
    selectedPetId = 0;
    tblPets.clearSelection();
    lblMessage.setText("");
}

private void showError(String message) {
    lblMessage.setForeground(Color.RED);
    lblMessage.setText(message);
}

private void showSuccess(String message) {
    lblMessage.setForeground(new Color(0, 128, 0));
    lblMessage.setText(message);
}

