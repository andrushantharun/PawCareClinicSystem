    private void tblPetsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPetsMouseClicked
         int row = tblPets.getSelectedRow();
    if (row == -1) return;

    DefaultTableModel model = (DefaultTableModel) tblPets.getModel();
    selectedPetId = (int) model.getValueAt(row, 0);
    String ownerName = (String) model.getValueAt(row, 1);
    for (int i = 0; i < cmbCustomer.getItemCount(); i++) {
        Customer c = (Customer) cmbCustomer.getItemAt(i);
        if (c.getFullName().equals(ownerName)) {
            cmbCustomer.setSelectedIndex(i);
            break;
        }
    }
    txtPetName.setText((String) model.getValueAt(row, 2));
    txtSpecies.setText((String) model.getValueAt(row, 3));
    txtBreed.setText((String) model.getValueAt(row, 4));
    txtAge.setText(String.valueOf(model.getValueAt(row, 5)));
    cmbGender.setSelectedItem((String) model.getValueAt(row, 6));
    lblMessage.setText("");
    }//GEN-LAST:event_tblPetsMouseClicked

    

